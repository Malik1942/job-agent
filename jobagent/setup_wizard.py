def _esc(v: Any) -> str:
    return html.escape(str(v or ""), quote=True)


def _inp(state: WizardState, name: str, placeholder: str = "",
         errors: set | None = None, label: str = "", required: bool = False,
         wide: bool = False) -> str:
    val = _esc(state.get(name, ""))
    cls = ' class="invalid"' if errors and name in errors else ""
    req = ' <span class="req">*</span>' if required else ""
    value = f' value="{val}"' if val else ""
    div = ' class="wide"' if wide else ""
    return (f'<div{div}><label>{label}{req}</label>'
            f'<input type="text" name="{name}"{value}'
            f' placeholder="{_esc(placeholder)}"{cls}></div>')


def _ta(state: WizardState, name: str, placeholder: str = "",
        errors: set | None = None, label: str = "", required: bool = False,
        rows: int = 3) -> str:
    val = _esc(state.get(name, ""))
    cls = ' class="invalid"' if errors and name in errors else ""
    req = ' <span class="req">*</span>' if required else ""
    return (f'<div class="wide"><label>{label}{req}</label>'
            f'<textarea name="{name}" rows="{rows}"'
            f' placeholder="{_esc(placeholder)}"{cls}>{val}</textarea></div>')


def _radio(state: WizardState, name: str, options: list[tuple[str, str]],
           errors: set | None = None, label: str = "",
           required: bool = False) -> str:
    cls = "radio-row invalid" if errors and name in errors else "radio-row"
    req = ' <span class="req">*</span>' if required else ""
    current = str(state.get(name, ""))
    rows = "".join(
        f'<label><input type="radio" name="{name}" value="{_esc(v)}"'
        f'{" checked" if current == v else ""}> {_esc(text)}</label>'
        for v, text in options)
    return f'<label>{label}{req}</label><div class="{cls}">{rows}</div>'


def _letters_ok(state: WizardState) -> set:
    """Field-error set for the cover-letters step (empty == valid)."""
    errors: set = set()
    families = state.get("families") or {}
    if not families:
        errors.add("family_0_name")
        errors.add("family_0_identity")
        errors.add("family_0_craft")
        return errors
    for i, (name, fam) in enumerate(families.items()):
        if not str(fam.get("identity", "")).strip():
            errors.add(f"family_{i}_identity")
        if not str(fam.get("craft", "")).strip():
            errors.add(f"family_{i}_craft")
    return errors


def _step_errors(idx: int, state: WizardState) -> set:
    key, _, required = STEPS[idx]
    errors = {f for f in required if not str(state.get(f, "")).strip()}
    if key == "letters":
        errors |= _letters_ok(state)
    return errors


