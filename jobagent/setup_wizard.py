def _csv(value: str) -> list[str]:
    return [x.strip() for x in str(value or "").split(",") if x.strip()]


def build_config_yaml(state: WizardState) -> str:
    """config.yaml text from wizard state. Only wizard-scope sections are
    emitted; everything else keeps the code defaults (documented in
    config.example.yaml). Safety: autonomy is pinned to review/no-live."""
    sources = []
    tokens: dict[str, list[str]] = {}
    for line in str(state.get("source_tokens", "")).splitlines():
        line = line.strip()
        if not line or ":" not in line:
            continue
        kind, token = line.split(":", 1)
        tokens.setdefault(kind.strip(), []).append(token.strip())
    for kind in state.get("sources", []):
        for token in tokens.get(kind, [""]):
            sources.append({"kind": kind, "token": token})

    variants = []
    for v in state.get("resume_variants", []):
        if str(v.get("path", "")).strip():
            variants.append({
                "keywords": _csv(v.get("keywords", "")),
                "path": str(v["path"]).strip(),
            })

    families: dict[str, dict] = {}
    for name, fam in (state.get("families") or {}).items():
        families[name] = {
            "keywords": _csv(fam.get("keywords", "")),
            "identity": str(fam.get("identity", "")).strip(),
            "craft": str(fam.get("craft", "")).strip(),
            "closing_mix": str(fam.get("closing_mix", "")).strip(),
            "marker": str(fam.get("marker", "")).strip().lower(),
        }
    projects = []
    for pr in state.get("projects", []):
        if str(pr.get("text", "")).strip():
            projects.append({
                "keywords": _csv(pr.get("keywords", "")),
                "text": str(pr["text"]).strip(),
            })

    profile: dict[str, Any] = {
        "name": str(state.get("full_name") or
                    f"{state.get('first_name', '')} {state.get('last_name', '')}").strip(),
        "email": str(state.get("email", "")).strip(),
        "phone": str(state.get("phone", "")).strip(),
        "location": str(state.get("location", "")).strip(),
        "website": str(state.get("website", "")).strip(),
        "linkedin": str(state.get("linkedin", "")).strip(),
        "pronouns": str(state.get("pronouns", "")).strip(),
        "summary": str(state.get("facts_background", "")).strip(),
        "titles": _csv(state.get("titles", "")),
        "skills": _csv(state.get("skills", "")),
        "locations": ([] if state.get("remote_ok") == "yes" and
                      not _csv(state.get("locations", ""))
                      else _csv(state.get("locations", ""))),
        "resume_path": str(state.get("resume_default", "")).strip(),
        "answers_path": "answers.md",
    }
    if variants:
        profile["resume_variants"] = variants

    data = {
        "profile": profile,
        "autonomy": {"mode": "review", "live_submit": False},
        "filters": {"exclude_keywords": _csv(state.get("exclude_keywords", ""))},
        "coverletter": {
            "default_family": (next(iter(families)) if families else ""),
            "families": families,
            "projects": projects,
        },
        "sources": sources,
    }
    header = (
        "# Generated by `jobagent setup` on {}.\n"
        "# Safe defaults: nothing is submitted until you set autonomy.mode: auto\n"
        "# AND autonomy.live_submit: true. Advanced settings (Slack, email\n"
        "# verification, scoring weights, schedules) keep their defaults —\n"
        "# see config.example.yaml for every option, and re-run\n"
        "# `jobagent setup` any time to edit this file.\n"
    ).format(time.strftime("%Y-%m-%d %H:%M"))
    return header + yaml.safe_dump(data, sort_keys=False, allow_unicode=True,
                                   default_flow_style=False)


def build_answers_md(state: WizardState) -> str:
    """answers.md text from wizard state, in the format AnswerBook parses
    (## Fields / ## Questions / ## Context)."""
    auth_text = {
        "yes": "Authorized to work in the US",
        "yes_limited": "Authorized to work with a time limit",
        "no": "Not currently authorized",
    }.get(str(state.get("auth_status", "")), "")
    sponsorship = "Yes" if state.get("sponsorship") == "yes" else "No"

    lines = ["# Application Answers", "",
             "# Generated by `jobagent setup`. Add more lines any time —",
             "# the filler holds any REQUIRED field it cannot answer from here.",
             "", "## Fields"]
    for key, src in [
        ("first_name", "first_name"), ("last_name", "last_name"),
        ("full_name", "full_name"), ("email", "email"), ("phone", "phone"),
        ("location", "location"), ("state", "state"),
        ("linkedin", "linkedin"), ("website", "website"), ("github", "github"),
        ("pronouns", "pronouns"), ("phonetic_name", "phonetic_name"),
    ]:
        val = str(state.get(src, "")).strip()
        if val:
            lines.append(f"- {key}: {val}")
    lines.append(f"- work_authorization: {auth_text}")
    lines.append(f"- require_sponsorship: {sponsorship}")
    notes = str(state.get("auth_notes", "")).strip()
    if notes:
        lines.append(f"- work_authorization_notes: {notes}")
    lines += [
        "Voluntary EEO questions. Leave as-is to decline, or edit.",
        "- gender: Decline to self-identify",
        "- hispanic_latino: Decline to self-identify",
        "- race: Decline to self-identify",
        "- veteran_status: Decline to self-identify",
        "- disability_status: Decline to self-identify",
        "", "## Questions",
    ]
    standard = str(state.get("facts_standard", "")).strip()
    if standard:
        lines.append(standard)
    lines += ["", "## Context"]
    for part in ("facts_background", "facts_projects"):
        val = str(state.get(part, "")).strip()
        if val:
            lines.append(val)
    return "\n".join(lines).rstrip() + "\n"


def _atomic_write(path: Path, text: str) -> None:
    if path.exists():
        bak = path.with_name(f"{path.name}.bak-{time.strftime('%Y%m%d-%H%M%S')}")
        bak.write_text(path.read_text(encoding="utf-8"), encoding="utf-8")
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)


def write_outputs(state: WizardState, config_path: Path,
                  answers_path: Path) -> list[str]:
    config_path = Path(config_path)
    answers_path = Path(answers_path)
    _atomic_write(config_path, build_config_yaml(state))
    _atomic_write(answers_path, build_answers_md(state))
    return [str(config_path), str(answers_path)]


def state_from_existing(config_path: Path, answers_path: Path) -> WizardState:
    """Pre-seed the wizard from existing files so re-running edits them.
    Best-effort: unreadable/missing files just mean an empty seed."""
    state: WizardState = {}
    try:
        from .config import load_config
        cfg = load_config(config_path)
    except Exception:
        return state
    p = cfg.profile
    parts = p.name.split(None, 1)
    state.update({
        "first_name": parts[0] if parts else "",
        "last_name": parts[1] if len(parts) > 1 else "",
        "full_name": p.name, "email": p.email, "phone": p.phone,
        "location": p.location, "website": p.website, "linkedin": p.linkedin,
        "pronouns": p.pronouns,
        "titles": ", ".join(p.titles), "skills": ", ".join(p.skills),
        "locations": ", ".join(p.locations),
        "remote_ok": "yes" if not p.locations else "no",
        "exclude_keywords": ", ".join(cfg.filters.exclude_keywords),
        "resume_default": p.resume_path,
        "resume_variants": [
            {"keywords": ", ".join(v.keywords), "path": v.path}
            for v in p.resume_variants
        ],
        "sources": sorted({s.kind for s in cfg.sources}),
        "source_tokens": "\n".join(
            f"{s.kind}:{s.token}" for s in cfg.sources if s.token),
        "families": {
            name: {"keywords": ", ".join(f.keywords), "identity": f.identity,
                   "craft": f.craft, "closing_mix": f.closing_mix,
                   "marker": f.marker}
            for name, f in cfg.coverletter.families.items()
        },
        "projects": [
            {"keywords": ", ".join(pr.keywords), "text": pr.text}
            for pr in cfg.coverletter.projects
        ],
        "facts_background": p.summary,
    })
    return state


