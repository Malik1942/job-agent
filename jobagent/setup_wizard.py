class _WizardHandler(BaseHTTPRequestHandler):
    session: dict = {}

    def log_message(self, fmt, *args):  # quiet server
        pass

    def _deny(self):
        self.send_response(403)
        self.send_header("Content-Type", "text/plain; charset=utf-8")
        self.end_headers()
        self.wfile.write(b"Forbidden: bad or missing token")

    def _page(self, html_text: str, status: int = 200):
        data = html_text.encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "text/html; charset=utf-8")
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        self.wfile.write(data)

    def _check_token(self, qs: dict) -> bool:
        return (qs.get("token") or [""])[0] == self.session["token"]

    def do_GET(self):
        url = urlparse(self.path)
        qs = parse_qs(url.query)
        if not self._check_token(qs):
            return self._deny()
        state = self.session["state"]
        token = self.session["token"]
        if url.path in ("/", "/setup"):
            try:
                idx = max(0, min(len(STEPS) - 1,
                                 int((qs.get("step") or ["0"])[0])))
            except ValueError:
                idx = 0
            return self._page(_render_step(idx, state, token))
        self._page("<h1>Not found</h1>", 404)

    def do_POST(self):
        url = urlparse(self.path)
        qs = parse_qs(url.query)
        if not self._check_token(qs):
            return self._deny()
        state = self.session["state"]
        token = self.session["token"]
        length = int(self.headers.get("Content-Length") or 0)
        body = self.rfile.read(length) if length else b""
        ctype = self.headers.get("Content-Type") or ""

        if url.path == "/finish":
            cfg_path = Path(self.session["config_path"])
            ans_path = cfg_path.parent / "answers.md"
            before = {p.name for p in cfg_path.parent.glob("*.bak-*")}
            written = write_outputs(state, cfg_path, ans_path)
            baks = sorted(
                p.name for p in cfg_path.parent.glob("*.bak-*")
                if p.name not in before)
            return self._page(_render_done(written, baks, token))

        if url.path != "/setup":
            return self._page("<h1>Not found</h1>", 404)

        try:
            idx = max(0, min(len(STEPS) - 1, int((qs.get("step") or ["0"])[0])))
        except ValueError:
            idx = 0

        if ctype.startswith("multipart/form-data"):
            parts = _parse_multipart(body, ctype)
            fields = {}
            for name, (fname, data) in parts.items():
                if name == "resume_file" and fname:
                    saved = _save_resume(
                        Path(self.session["config_path"]).parent, fname, data)
                    if saved:
                        fields["resume_default"] = saved
                elif not fname:
                    fields[name] = [data.decode("utf-8", "replace")]
            form = fields
        else:
            form = parse_qs(body.decode("utf-8", "replace"),
                            keep_blank_values=True)

        _apply_form(idx, form, state)
        errors = _step_errors(idx, state)
        if errors:
            return self._page(_render_step(idx, state, token, errors=errors))
        nxt = min(len(STEPS) - 1, idx + 1)
        return self._page(_render_step(nxt, state, token))


def _apply_form(idx: int, form: dict, state: WizardState) -> None:
    """Merge one step's POSTed fields into the wizard state."""
    key = STEPS[idx][0]

    def first(name: str) -> str:
        return (form.get(name) or [""])[0]

    simple = {
        "basics": ["first_name", "last_name", "email", "phone", "location",
                   "state", "phonetic_name", "pronouns", "website",
                   "linkedin", "github"],
        "workauth": ["auth_status", "sponsorship", "auth_notes"],
        "targeting": ["titles", "skills", "exclude_keywords", "remote_ok",
                      "locations", "source_tokens"],
        "resumes": ["resume_default"],
        "facts": ["facts_background", "facts_projects", "facts_standard"],
    }.get(key, [])
    for name in simple:
        if name in form:
            state[name] = first(name)
    if key == "basics":
        state["full_name"] = (
            f"{state.get('first_name', '')} {state.get('last_name', '')}"
        ).strip()
    if key == "targeting":
        state["sources"] = [
            s for s in (form.get("sources") or []) if s in SOURCE_KINDS]
    if key == "resumes":
        variants = []
        for i in range(3):
            path = first(f"variant_{i}_path").strip()
            if path:
                variants.append({
                    "path": path,
                    "keywords": first(f"variant_{i}_keywords"),
                })
        state["resume_variants"] = variants
    if key == "letters":
        families: dict = {}
        for i in range(3):
            name = re.sub(r"[^a-z0-9_]", "",
                          first(f"family_{i}_name").strip().lower()
                          .replace(" ", "_"))
            if not name:
                continue
            families[name] = {
                "keywords": first(f"family_{i}_keywords"),
                "identity": first(f"family_{i}_identity"),
                "craft": first(f"family_{i}_craft"),
                "closing_mix": first(f"family_{i}_closing_mix"),
                "marker": (first(f"family_{i}_marker").strip().lower()
                           or name.replace("_", " ")),
            }
        state["families"] = families
        projects = []
        for i in range(3):
            text = first(f"project_{i}_text").strip()
            if text:
                projects.append({
                    "keywords": first(f"project_{i}_keywords"),
                    "text": text,
                })
        state["projects"] = projects


def _parse_multipart(body: bytes, content_type: str) -> dict[str, tuple[str, bytes]]:
    """name -> (filename, data) for a multipart/form-data body. Minimal:
    enough for one small PDF + text fields, not a general parser."""
    m = re.search(r'boundary="?([^";]+)"?', content_type)
    if not m:
        return {}
    boundary = b"--" + m.group(1).encode()
    out: dict[str, tuple[str, bytes]] = {}
    for part in body.split(boundary):
        if b"\r\n\r\n" not in part:
            continue
        head, _, data = part.partition(b"\r\n\r\n")
        data = data.rstrip(b"\r\n-")
        name_m = re.search(rb'name="([^"]+)"', head)
        if not name_m:
            continue
        file_m = re.search(rb'filename="([^"]*)"', head)
        fname = file_m.group(1).decode("utf-8", "replace") if file_m else ""
        out[name_m.group(1).decode()] = (fname, data)
    return out


def _save_resume(dest_dir: Path, filename: str, data: bytes) -> str:
    """Save an uploaded resume PDF next to config.yaml. Returns the saved
    basename, or '' when rejected (wrong type / too large / empty)."""
    base = os.path.basename(filename).strip()
    if not base.lower().endswith(".pdf") or not data:
        return ""
    if len(data) > 10 * 1024 * 1024:
        return ""
    base = re.sub(r"[^A-Za-z0-9._ -]", "_", base)
    dest_dir.mkdir(parents=True, exist_ok=True)
    (dest_dir / base).write_bytes(data)
    return base


def _make_server(config_path: str, host: str = "127.0.0.1", port: int = 0):
    """(server, token, url). Exposed for tests; run_setup_wizard drives it."""
    cfg_path = Path(config_path)
    token = os.getenv("JOBAGENT_SETUP_TOKEN") or token_urlsafe(24)
    state = state_from_existing(cfg_path, cfg_path.parent / "answers.md")

    handler = type("BoundWizardHandler", (_WizardHandler,), {
        "session": {"token": token, "state": state,
                    "config_path": str(cfg_path)},
    })
    server = ThreadingHTTPServer((host, port), handler)
    url = f"http://{host}:{server.server_address[1]}/setup?token={token}&step=0"
    return server, token, url


def run_setup_wizard(config_path: str, host: str = "127.0.0.1",
                     port: int = 0, open_browser: bool = True) -> None:
    server, _token, url = _make_server(config_path, host=host, port=port)
    print("jobagent setup wizard running (local only):")
    print(f"  {url}")
    print("Press Ctrl-C when you are done.")
    if open_browser:
        threading.Timer(0.3, webbrowser.open, args=(url,)).start()
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nsetup wizard stopped")
    finally:
        server.server_close()
